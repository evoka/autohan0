#!/usr/bin/env node
// Parse libhangul keyboard XML templates (data/libhangul) into a compact JSON table
// used by the engine. Adding another Sebeolsik layout only needs another XML file
// listed in LAYOUTS below.
//
// Usage: node scripts/build_layouts.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'data', 'libhangul');
const outFile = join(root, 'packages', 'engine', 'src', 'generated', 'layouts.json');

const LAYOUTS = [
  { id: '3f', file: 'hangul-keyboard-3f.xml.template', label: '세벌식 최종' },
  { id: '39', file: 'hangul-keyboard-39.xml.template', label: '세벌식 390' },
];

const hex = (s) => String.fromCodePoint(parseInt(s, 16));

function parseKeyboard(xml) {
  const name = (xml.match(/<name>([^<]*)<\/name>/) || [])[1] || '';
  const type = (xml.match(/<hangul-keyboard[^>]*type="([^"]+)"/) || [])[1] || '';
  const map = {};
  // Only map id="0" (the base map) is used by libhangul for these layouts.
  const base = xml.match(/<map id="0">([\s\S]*?)<\/map>/);
  if (!base) throw new Error('map id=0 not found');
  for (const m of base[1].matchAll(/key="0x([0-9a-fA-F]+)"\s+value="0x([0-9a-fA-F]+)"/g)) {
    map[hex(m[1])] = hex(m[2]);
  }
  const includes = [...xml.matchAll(/<include file="([^"]+)"\/>/g)].map((m) => m[1]);
  return { name, type, map, includes };
}

function parseCombination(xml) {
  const out = [];
  for (const m of xml.matchAll(/first="0x([0-9a-fA-F]+)"\s+second="0x([0-9a-fA-F]+)"\s+result="0x([0-9a-fA-F]+)"/g)) {
    out.push([hex(m[1]), hex(m[2]), hex(m[3])]);
  }
  return out;
}

const combinations = {};
const layouts = {};
for (const def of LAYOUTS) {
  const kb = parseKeyboard(readFileSync(join(srcDir, def.file), 'utf8'));
  if (kb.type !== 'jaso') throw new Error(`${def.id}: expected jaso keyboard, got ${kb.type}`);
  const combo = kb.includes.find((f) => f.startsWith('hangul-combination')) || 'hangul-combination-default.xml';
  const comboId = combo.replace(/^hangul-combination-|\.xml$/g, '');
  if (!combinations[comboId]) combinations[comboId] = parseCombination(readFileSync(join(srcDir, combo), 'utf8'));
  layouts[def.id] = { id: def.id, label: def.label, name: kb.name, combination: comboId, map: kb.map };
  console.log(`${def.id}: ${Object.keys(kb.map).length} keys, combination=${comboId}`);
}

const out = {
  source: 'libhangul (https://github.com/libhangul/libhangul), LGPL-2.1 — generated by scripts/build_layouts.mjs',
  layouts,
  combinations,
};
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, JSON.stringify(out, null, 0) + '\n');
console.log(`wrote ${outFile}`);
